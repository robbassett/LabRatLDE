const ingestBatch = 5000

type instrument struct {
	ID     string         `json:"id"`
	NodeID string         `json:"node_id"`
	Name   string         `json:"name"`
	Kind   string         `json:"kind"`
	Attrs  map[string]any `json:"attrs,omitempty"`
}

func (s *Server) createInstrument(w http.ResponseWriter, r *http.Request) {
	ctx, p := r.Context(), principal(r.Context())
	var in instrument
	if err := decodeJSON(w, r, &in); err != nil {
		s.fail(w, r, err)
		return
	}
	if in.Name == "" || in.Kind == "" {
		s.fail(w, r, badRequest("name and kind are required"))
		return
	}
	if in.Attrs == nil {
		in.Attrs = map[string]any{}
	}
	err := s.db.WithTenant(ctx, p.Tenant, p.As, func(tx pgx.Tx) (err error) {
		if in.NodeID, err = insertNode(ctx, tx, p, domain.KindInstrument, in.Name, map[string]any{"instrument_kind": in.Kind}); err != nil {
			return err
		}
		if err = tx.QueryRow(ctx, `
			INSERT INTO instruments (tenant_id, node_id, name, kind, attrs)
			VALUES ($1, $2, $3, $4, $5) RETURNING id`,
			p.Tenant, in.NodeID, in.Name, in.Kind, in.Attrs).Scan(&in.ID); err != nil {
			return err
		}
		_, err = audit.Append(ctx, tx, p.Tenant, audit.Entry{
			Actor: p.Actor, Action: "instrument.registered", EntityType: "instrument", EntityID: in.ID, Payload: in,
		})
		return err
	})
	if err != nil {
		s.fail(w, r, err)
		return
	}
	writeJSON(w, http.StatusCreated, in)
}

// listInstruments pages through instruments in name order (name is unique per
// tenant). The cursor is the id of the last instrument on the previous page.
//
//	GET /v1/instruments?cursor=<uuid>&limit=<1..200>
func (s *Server) listInstruments(w http.ResponseWriter, r *http.Request) {
	ctx, p := r.Context(), principal(r.Context())
	cursor, limit, err := readPage(r)
	if err != nil {
		s.fail(w, r, err)
		return
	}
	type summary struct {
		ID        string         `json:"id"`
		NodeID    string         `json:"node_id"`
		Name      string         `json:"name"`
		Kind      string         `json:"kind"`
		Attrs     map[string]any `json:"attrs"`
		CreatedAt time.Time      `json:"created_at"`
	}
	items := []summary{}
	err = s.db.WithTenant(ctx, p.Tenant, p.As, func(tx pgx.Tx) error {
		rows, err := tx.Query(ctx, `
			SELECT id, node_id, name, kind, attrs, created_at FROM instruments
			WHERE ($1::text = '' OR name > (SELECT name FROM instruments WHERE id = NULLIF($1::text, '')::uuid))
			ORDER BY name
			LIMIT $2`, cursor, limit)
		if err != nil {
			return err
		}
		defer rows.Close()
		for rows.Next() {
			var in summary
			if err := rows.Scan(&in.ID, &in.NodeID, &in.Name, &in.Kind, &in.Attrs, &in.CreatedAt); err != nil {
				return err
			}
			if in.Attrs == nil {
				in.Attrs = map[string]any{}
			}
			items = append(items, in)
		}
		return rows.Err()
	})
	if err != nil {
		s.fail(w, r, err)
		return
	}
	var last string
	if n := len(items); n > 0 {
		last = items[n-1].ID
	}
	writeJSON(w, http.StatusOK, page{Items: items, NextCursor: nextCursor(len(items), limit, last)})
}

// streamReadings ingests an NDJSON stream of readings from an instrument.
//
//	POST /v1/instruments/{id}/stream?run_id=<uuid>&label=<text>
//	Content-Type: application/x-ndjson
//
// Each upload becomes one `dataset` lineage node, attributed to the
// instrument and (optionally) generated by a run. The upload is atomic, and
// its audit event pins the SHA-256 of the exact bytes received.
//
// The body is saved to a temp file before the write transaction opens, so a slow
// client holds no database connection or lock (SPEC-023-R01).
func (s *Server) streamReadings(w http.ResponseWriter, r *http.Request) {
	ctx, p := r.Context(), principal(r.Context())
	instID, runID, label := r.PathValue("id"), r.URL.Query().Get("run_id"), r.URL.Query().Get("label")
	if !validUUID(instID) {
		s.fail(w, r, notFound("instrument"))
		return
	}
	if runID != "" && !validUUID(runID) {
		s.fail(w, r, badRequest("run_id must be a uuid"))
		return
	}

	// Find the instrument and run first, so a bad id fails before the upload is read.
	up := upload{instrumentID: instID, runID: runID, label: label}
	err := s.db.WithTenant(ctx, p.Tenant, p.As, func(tx pgx.Tx) error { return up.resolve(ctx, tx) })
	if err != nil {
		s.fail(w, r, err)
		return
	}

	spool, err := spoolBody(http.MaxBytesReader(w, r.Body, s.cfg.MaxIngestBytes))
	if err != nil {
		s.fail(w, r, err)
		return
	}
	defer func() {
		_ = spool.Close()
		_ = os.Remove(spool.Name())
	}()

	var resp struct {
		DatasetID string `json:"dataset_id"`
		ingest.Summary
	}
	err = s.db.WithTenant(ctx, p.Tenant, p.As, func(tx pgx.Tx) (err error) {
		resp.DatasetID, resp.Summary, err = up.store(ctx, tx, p, spool)
		return err
	})
	if err != nil {
		s.fail(w, r, err)
		return
	}
	writeJSON(w, http.StatusCreated, resp)
}

// spoolBody copies an upload to a temp file, ready to read from the start. The
// caller closes and removes it. On an error nothing is left behind.
func spoolBody(body io.Reader) (*os.File, error) {
	f, err := os.CreateTemp("", "labrat-ingest-*")
	if err != nil {
		return nil, err
	}
	_, err = io.Copy(f, body)
	if err == nil {
		_, err = f.Seek(0, io.SeekStart)
	}
	if err != nil {
		_ = f.Close()
		_ = os.Remove(f.Name())
		return nil, err
	}
	return f, nil
}

// upload is where one instrument upload's readings belong.
type upload struct {
	instrumentID, runID, label string
	instrumentNode, runNode    string
}

// resolve refuses a caller who couldn't store the readings, so they can't fill
// the temp disk (SPEC-023-R12; the database's role gate is what enforces it). It
// then finds the lineage nodes the dataset will link to, and its default label.
func (u *upload) resolve(ctx context.Context, tx pgx.Tx) error {
	var allowed bool
	if err := tx.QueryRow(ctx, `SELECT lde_has_role('scientist')`).Scan(&allowed); err != nil {
		return err
	}
	if !allowed {
		return forbidden("uploading readings needs the scientist role")
	}
	var name string
	err := tx.QueryRow(ctx, `SELECT node_id, name FROM instruments WHERE id = $1`, u.instrumentID).Scan(&u.instrumentNode, &name)
	if errors.Is(err, pgx.ErrNoRows) {
		return notFound("instrument")
	} else if err != nil {
		return err
	}
	if u.label == "" {
		u.label = name + " stream"
	}
	if u.runID == "" {
		return nil
	}
	err = tx.QueryRow(ctx, `SELECT node_id FROM runs WHERE id = $1`, u.runID).Scan(&u.runNode)
	if errors.Is(err, pgx.ErrNoRows) {
		return notFound("run")
	}
	return err
}

// store writes the dataset, its readings and their audit events. The chain lock
// is first taken after the readings are in, so parsing a large file doesn't stop
// other writes in the tenant (SPEC-023-R02). The audit events commit with the
// readings, and the edge trigger still refuses a sealed run.
func (u *upload) store(ctx context.Context, tx pgx.Tx, p Principal, src io.Reader) (string, ingest.Summary, error) {
	attrs := map[string]any{"instrument_id": u.instrumentID, "source_media_type": "application/x-ndjson"}
	dsID, err := insertNodeRow(ctx, tx, p, domain.KindDataset, u.label, attrs)
	if err != nil {
		return "", ingest.Summary{}, err
	}
	sum, err := ingest.Decode(src, ingestBatch, func(batch []ingest.Reading) error {
		return insertReadings(ctx, tx, p.Tenant, u.instrumentID, dsID, batch)
	})
	if err != nil {
		return "", sum, err
	}
	if sum.Count == 0 {
		return "", sum, badRequest("stream contained no readings")
	}
	if err := auditNodeCreated(ctx, tx, p, dsID, domain.KindDataset, u.label, attrs); err != nil {
		return "", sum, err
	}
	if err := insertEdge(ctx, tx, p, domain.Edge{From: u.instrumentNode, To: dsID, Relation: domain.RelWasAttributedTo}); err != nil {
		return "", sum, err
	}
	if u.runID != "" {
		if err := insertEdge(ctx, tx, p, domain.Edge{From: u.runNode, To: dsID, Relation: domain.RelWasGeneratedBy}); err != nil {
			return "", sum, err
		}
	}
	_, err = audit.Append(ctx, tx, p.Tenant, audit.Entry{
		Actor: p.Actor, Action: "instrument.ingested", EntityType: "dataset", EntityID: dsID,
		Payload: map[string]any{
			"instrument_id": u.instrumentID, "run_id": u.runID, "count": sum.Count, "sha256": sum.SHA256,
			"first_ts": sum.First, "last_ts": sum.Last,
		},
	})
	return dsID, sum, err
}

// insertReadings stores one batch. COPY FROM is unavailable on RLS-protected
// tables, so it goes in as one array-unnest INSERT: a single round trip.
func insertReadings(ctx context.Context, tx pgx.Tx, tenant, instrumentID, datasetID string, batch []ingest.Reading) error {
	ts := make([]time.Time, len(batch))
	ch := make([]string, len(batch))
	val := make([]float64, len(batch))
	unit := make([]string, len(batch))
	for i, rd := range batch {
		ts[i], ch[i], val[i], unit[i] = rd.TS, rd.Channel, rd.Value, rd.Unit
	}
	_, err := tx.Exec(ctx, `
		INSERT INTO instrument_readings (tenant_id, instrument_id, dataset_id, ts, channel, value, unit)
		SELECT $1::uuid, $2::uuid, $3::uuid, t.ts, t.channel, t.value, t.unit
		FROM unnest($4::timestamptz[], $5::text[], $6::float8[], $7::text[]) AS t (ts, channel, value, unit)`,
		tenant, instrumentID, datasetID, ts, ch, val, unit)
	return err
}
